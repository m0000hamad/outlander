def normalise(lang: str | None) -> str:
    value = (lang or "").strip().lower()
    return value if value in LANGS else DEFAULT_LANG


def t(lang: str, key: str, **params: object) -> str:
    table = TRANSLATIONS[normalise(lang)]
    text = table.get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key
    return text.format(**params) if params else text


def direction(lang: str) -> str:
    return "rtl" if normalise(lang) == "fa" else "ltr"
